export type Chiave = keyof (typeof TESTI)['it']

let corrente: Lingua = 'it'
try {
  const salvata = localStorage.getItem(CHIAVE)
  if (salvata === 'it' || salvata === 'ro') corrente = salvata
} catch {
  /* modalità privata: resta l'italiano */
}

/** Traduce una chiave. Se manca nella lingua scelta si ripiega sull'italiano. */
export function t(c: Chiave): string {
  return (TESTI[corrente] as Record<string, string>)[c] ?? TESTI.it[c] ?? c
}

export function lingua(): Lingua {
  return corrente
}

/** Codice locale per date e numeri, allineato alla lingua scelta. */
export function locale(): string {
  return corrente === 'ro' ? 'ro-RO' : 'it-IT'
}

/**
 * Cambia lingua e ricarica: tutti i testi sono già stampati nel DOM, e
 * ridisegnare a mano ogni pagina costerebbe più codice di quanto valga per
 * un'azione che si fa una volta sola.
 */
export function cambiaLingua(l: Lingua): void {
  corrente = l
  try {
    localStorage.setItem(CHIAVE, l)
  } catch {
    /* la scelta vale per questa sessione */
  }
  location.reload()
}

