/** "1 settembre 2026". Stringa vuota se la data non si legge. */
export function dataLeggibile(iso: string): string {
  const d = new Date(iso)
  if (Number.isNaN(d.getTime())) return ''
  return d.toLocaleDateString(locale(), { day: 'numeric', month: 'long', year: 'numeric' })
}

/** "01 set 2026", per le tabelle. */
export function dataBreve(iso: string): string {
  const d = new Date(iso)
  if (Number.isNaN(d.getTime())) return ''
  return d.toLocaleDateString(locale(), { day: '2-digit', month: 'short', year: 'numeric' })
}

/** "1 set, 14:30". */
export function dataOra(iso: string): string {
  const d = new Date(iso)
  if (Number.isNaN(d.getTime())) return ''
  return d.toLocaleString(locale(), { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' })
}

/**
 * "adesso", "12 min fa", "3 ore fa", "ieri", "5 giorni fa", poi la data.
 * Per le richieste: quanto tempo aspetta una persona conta più della data.
 */
export function tempoFa(iso: string): string {
  const d = new Date(iso)
  if (Number.isNaN(d.getTime())) return ''
  const secondi = Math.max(0, (Date.now() - d.getTime()) / 1000)
  if (secondi < 90) return t('comune.adesso')
  const minuti = Math.round(secondi / 60)
  if (minuti < 60) return `${minuti} ${t('comune.minutiFa')}`
  const ore = Math.round(minuti / 60)
  if (ore < 24) return `${ore} ${t('comune.oreFa')}`
  const giorni = Math.round(ore / 24)
  if (giorni === 1) return t('comune.ieri')
  if (giorni < 7) return `${giorni} ${t('comune.giorniFa')}`
  return dataBreve(iso)
}

/** I numeri escono con il separatore delle migliaia della lingua scelta. */
export function numero(n: number): string {
  return n.toLocaleString(locale())
}
